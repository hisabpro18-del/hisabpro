// Builds the desktop (SQLite) database from the Postgres schema:
//   prisma/sqlite/schema.prisma  → the same models for SQLite (server-only tables left out)
//   src/generated/sqlite         → its Prisma client (with the Windows engine as well, for the .exe)
//   desktop/schema.sql           → CREATE TABLE … plus the outbox triggers, run by a PC on first start
// Statements in schema.sql are separated by a line "-- @@" so the app can run them one by one.
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const { PUSHABLE } = require('../src/sync/registry');

const root = path.join(__dirname, '..');
const SERVER_ONLY = ['Device', 'ChangeLog', 'Secret'];
let s = fs.readFileSync(path.join(root, 'prisma', 'schema.prisma'), 'utf8');

s = s.replace(/generator client \{[\s\S]*?\}/, `generator client {
  provider      = "prisma-client-js"
  output        = "../../src/generated/sqlite"
  binaryTargets = ["native", "windows"]
}`);
s = s.replace(/datasource db \{[\s\S]*?\}/, `datasource db {
  provider     = "sqlite"
  url          = env("DATABASE_URL")
  relationMode = "prisma"
}`);
for (const m of SERVER_ONLY) s = s.replace(new RegExp(`(^|\\n)(//[^\\n]*\\n)*model ${m} \\{[\\s\\S]*?\\n\\}\\n`), '\n');
s = s.replace(/\s@db\.[A-Za-z]+(\([^)]*\))?/g, '');

const dir = path.join(root, 'prisma', 'sqlite');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'schema.prisma'), s);
console.log('wrote prisma/sqlite/schema.prisma');

execSync('npx prisma generate --schema prisma/sqlite/schema.prisma', { cwd: root, stdio: 'inherit', env: { ...process.env, DATABASE_URL: 'file:./dev.db' } });
const ddl = execSync('npx prisma migrate diff --from-empty --to-schema-datamodel prisma/sqlite/schema.prisma --script', { cwd: root, env: { ...process.env, DATABASE_URL: 'file:./dev.db' } }).toString();

// split the DDL into statements (Prisma's script has no semicolons inside statements)
const statements = ddl.split(/;\s*\n/).map(x => x.replace(/^--.*$/gm, '').trim()).filter(Boolean);
const extra = [
    'PRAGMA journal_mode=WAL',
    'CREATE TABLE IF NOT EXISTS "_outbox" ("id" INTEGER PRIMARY KEY AUTOINCREMENT, "tbl" TEXT NOT NULL, "rowId" TEXT NOT NULL, "at" TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP)',
    'CREATE INDEX IF NOT EXISTS "_outbox_row" ON "_outbox" ("tbl", "rowId")',
    'CREATE TABLE IF NOT EXISTS "_flags" ("k" TEXT PRIMARY KEY, "v" TEXT NOT NULL)',
    `INSERT OR IGNORE INTO "_flags" ("k", "v") VALUES ('applying', '0')`,
    'CREATE TABLE IF NOT EXISTS "_device" ("k" TEXT PRIMARY KEY, "v" TEXT NOT NULL)',
];
// every local insert/update of a table the PC sends up lands in the outbox — except while pulled rows are applied
const triggers = [];
for (const t of PUSHABLE) {
    for (const op of ['INSERT', 'UPDATE']) {
        triggers.push(`CREATE TRIGGER IF NOT EXISTS "ob_${t}_${op[0]}" AFTER ${op} ON "${t}" WHEN (SELECT "v" FROM "_flags" WHERE "k" = 'applying') = '0' BEGIN INSERT INTO "_outbox" ("tbl", "rowId") VALUES ('${t}', NEW."id"); END`);
    }
}
const all = [...extra, ...statements.map(x => x.replace(/^CREATE TABLE /, 'CREATE TABLE IF NOT EXISTS ').replace(/^CREATE (UNIQUE )?INDEX /, 'CREATE $1INDEX IF NOT EXISTS ')), ...triggers];
const version = require('crypto').createHash('sha256').update(all.join('\n')).digest('hex').slice(0, 12);
fs.writeFileSync(path.join(root, 'desktop', 'schema.sql'), `-- HisabPro desktop database, version ${version} (generated by scripts/gen-sqlite.js; do not edit)\n` + all.join('\n-- @@\n') + '\n');
console.log(`wrote desktop/schema.sql (${statements.length} tables/indexes, ${triggers.length} outbox triggers, version ${version})`);
